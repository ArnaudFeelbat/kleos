import { z } from 'zod';
import { TableRef } from './schema';

/**
 * Schema editing (0.6). The window stages a list of changes; the server turns each into
 * exactly one SQL statement — identifiers quoted, types resolved through Postgres — and the
 * same builder serves the preview and the run, so the SQL the user reads is the SQL that runs.
 * A run is one transaction: any failure rolls everything back and names the statement.
 *
 * Out of scope for 0.6: foreign keys and check constraints, CREATE INDEX CONCURRENTLY (not
 * allowed inside a transaction), partitioning, views.
 */

const identifier = z.string().min(1).max(63);

/**
 * A column type as the user writes it ("text", "varchar(80)", "numeric(12,2)", "timestamptz",
 * "int[]", "shop.order_status"). The server checks it with Postgres (`$1::regtype` and
 * format_type) and writes the canonical form into the SQL, so free text never reaches it raw.
 */
const columnType = z.string().trim().min(1).max(200);

export const ColumnSpec = z.object({
  name: identifier,
  type: columnType,
  nullable: z.boolean().default(true),
  /**
   * A SQL expression ("now()", "'draft'", "0"), written as typed into the statement. It is
   * the user's own SQL against their own database, like the query editor; the preview shows it.
   */
  default: z.string().max(2000).nullable().default(null),
});
export type ColumnSpec = z.input<typeof ColumnSpec>;

export const indexMethods = ['btree', 'hash', 'gin', 'gist', 'brin'] as const;

export const DdlChange = z.discriminatedUnion('op', [
  z.object({
    op: z.literal('createTable'),
    schema: identifier,
    name: identifier,
    columns: z.array(ColumnSpec).min(1).max(1600),
    /** Column names forming the primary key; empty for none. */
    primaryKey: z.array(identifier).default([]),
  }),
  z.object({ op: z.literal('renameTable'), table: TableRef, newName: identifier }),
  z.object({ op: z.literal('dropTable'), table: TableRef, cascade: z.boolean().default(false) }),
  z.object({ op: z.literal('addColumn'), table: TableRef, column: ColumnSpec }),
  z.object({ op: z.literal('renameColumn'), table: TableRef, column: identifier, newName: identifier }),
  z.object({
    op: z.literal('alterColumnType'),
    table: TableRef,
    column: identifier,
    type: columnType,
    /** Optional USING expression for conversions Postgres can't do implicitly. */
    using: z.string().max(2000).nullable().default(null),
  }),
  z.object({ op: z.literal('setNotNull'), table: TableRef, column: identifier, notNull: z.boolean() }),
  /** `default: null` drops the default. */
  z.object({
    op: z.literal('setDefault'),
    table: TableRef,
    column: identifier,
    default: z.string().max(2000).nullable(),
  }),
  z.object({ op: z.literal('dropColumn'), table: TableRef, column: identifier, cascade: z.boolean().default(false) }),
  z.object({
    op: z.literal('createIndex'),
    table: TableRef,
    /** Generated by Postgres when null. */
    name: identifier.nullable().default(null),
    columns: z.array(identifier).min(1).max(32),
    unique: z.boolean().default(false),
    method: z.enum(indexMethods).default('btree'),
  }),
  z.object({ op: z.literal('dropIndex'), schema: identifier, name: identifier, cascade: z.boolean().default(false) }),
]);
export type DdlChange = z.input<typeof DdlChange>;

/** Body of POST /sessions/:sid/ddl/preview and POST /sessions/:sid/ddl. */
export const DdlRequest = z.object({ changes: z.array(DdlChange).min(1).max(200) });
export type DdlRequest = z.input<typeof DdlRequest>;

/** One statement per change, in order. */
export const DdlPreview = z.object({ statements: z.array(z.string()) });
export type DdlPreview = z.infer<typeof DdlPreview>;

export const DdlResult = z.object({
  statements: z.array(z.string()),
  elapsedMs: z.number(),
});
export type DdlResult = z.infer<typeof DdlResult>;
